const RLM = '‏'

/** Arabic counting: 1 and 2 have their own forms, 3-10 take the plural, 11-99 the singular (accusative), 100+ by the last two digits. */
function arCount(n: number, one: string, two: string, plural: string, acc: string, gen: string): string {
  if (n === 1) return one
  if (n === 2) return two
  const t = n % 100
  if (t >= 3 && t <= 10) return `${n} ${plural}`
  if (t >= 11 && t <= 99) return `${n} ${acc}`
  return `${n} ${gen}`
}

