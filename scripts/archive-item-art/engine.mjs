// node scripts/archive-item-art/engine.mjs <app ref> [app repo]: bundles engine-entry.ts against the app's lib and
// localization at <ref> (git archive, no checkout) into src/lib/backdrop/engine.generated.js (minified ESM).
import { execSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = join(HERE, '..', '..');
const [ref, app = join(SITE, '..', 'spy-social')] = process.argv.slice(2);
if (!ref) { console.error('usage: node engine.mjs <app ref> [app repo]'); process.exit(2); }
const work = mkdtempSync(join(HERE, '.engine.'));
try {
  execSync(`git -C "${app}" archive "${ref}" lib localization | tar -x -C "${work}"`);
  copyFileSync(join(HERE, 'engine-entry.ts'), join(work, 'entry.ts'));
  const sha = execSync(`git -C "${app}" rev-parse --short "${ref}"`).toString().trim();
  const esbuild = createRequire(join(SITE, 'package.json'))('esbuild');
  const out = join(SITE, 'src/lib/backdrop/engine.generated.js');
  mkdirSync(dirname(out), { recursive: true });
  await esbuild.build({ entryPoints: [join(work, 'entry.ts')], bundle: true, format: 'esm', platform: 'neutral', minify: true, alias: { '@': work }, outfile: out, logLevel: 'warning', external: ['react', 'react-native', '@react-native-async-storage/async-storage'], legalComments: 'none' });
  const body = readFileSync(out, 'utf8');
  writeFileSync(out, `// GENERATED by scripts/archive-item-art/engine.mjs from the app at ${sha} (${ref}). Do not edit.\n` + body);
  console.log('engine', sha, Math.round(body.length / 1024), 'KB');
} finally {
  rmSync(work, { recursive: true, force: true });
}
